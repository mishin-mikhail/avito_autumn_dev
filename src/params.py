"""
Разбор поля параметров объявления на «услугу» и «адрес».

Поле item_infm_params_text - склеенные пары «ключ значение»:
    «Вид услуги Ремонт и отделка Место оказания услуг Москва, улица Цюрупы, 14Б Тип услуги Плиточные работы ...»
В v2 оно целиком шло в BM25, и адрес зашумлял текстовое совпадение (вес поля получился отрицательным).
Здесь из него выделяются:
  * service - значения «Вид услуги ...» и «Тип услуги ...» (что делает исполнитель);
  * place   - значение «Место оказания услуг ...» (где; нужен для запросов с городом в тексте).

Значение ключа «услуги» - первое слово с заглавной буквы и следующие за ним слова
со строчной (так устроены значения рубрикатора: «Маникюр, педикюр», «Ремонт квартир и домов под ключ»).
Адрес заканчивается там, где начинается один из следующих ключей.
"""
import re

from .filters import normalize_params

_NEXT_KEYS = r"Место оказания услуг|Тип стоимости|Тип услуги|Вид услуги|Работаете|Опыт работы|Онлайн-запись"
_SERVICE_RE = re.compile(
    r"(?:Вид услуги|Тип услуги(?: [а-я]+)?) (?!" + _NEXT_KEYS + r")([A-ZА-Я0-9][^ ]*(?: (?![A-ZА-Я])[^ ]+)*)")
_PLACE_RE = re.compile(
    r"Место оказания услуг (.*?)(?= (?:Тип |Вид услуги|Работаете|Опыт работы|Минимальн|Марка|Модель"
    r"|Стоимость|Цена|Онлайн-запись)|$)")


def service_text(params) -> str:
    """Значения рубрикатора услуг из параметров объявления, через пробел."""
    return " ".join(m.group(1) for m in _SERVICE_RE.finditer(normalize_params(params)))


def place_text(params) -> str:
    """Адрес «Место оказания услуг» из параметров объявления."""
    m = _PLACE_RE.search(normalize_params(params))
    return m.group(1) if m else ""
